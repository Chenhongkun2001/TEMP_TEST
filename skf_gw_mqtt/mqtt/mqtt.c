static unsigned int mqtt_get_retry_delay(uint32_t failure_count) {
  unsigned int retry_delay = MQTT_RETRY_BASE_DELAY_S;
  uint32_t backoff_step = failure_count / MQTT_RETRY_BACKOFF_STEP;

  while (backoff_step-- > 0 && retry_delay < MQTT_RETRY_MAX_DELAY_S) {
    if (retry_delay > (MQTT_RETRY_MAX_DELAY_S / 2U)) {
      retry_delay = MQTT_RETRY_MAX_DELAY_S;
      break;
    }
    retry_delay *= 2U;
  }
  return retry_delay;
}

static void mqtt_handle_connect_failure(int error_code, bool need_sleep) {
  unsigned int retry_delay = 0;

  app_io_post_led_event(LED_EV_MQTT_ERR);
  if (disconnectCnt < UINT32_MAX) {
    disconnectCnt++;
  }
  if (networkToggleCooldown > 0) {
    networkToggleCooldown--;
  }

  retry_delay = mqtt_get_retry_delay(disconnectCnt);
  LOG_WARN(OUTPOINT,
           "MQTT reconnect failed:%d streak:%u retry in %u s cooldown:%u\r\n",
           error_code, disconnectCnt, retry_delay, networkToggleCooldown);

  if (disconnectCnt >= MQTT_TOGGLE_THRESHOLD) {
    if (networkToggleCooldown == 0) {
      LOG_WARN(OUTPOINT, "MQTT reconnect threshold reached, toggle network\r\n");
      toggleNetwork();
      networkToggleCooldown = MQTT_TOGGLE_COOLDOWN_ATTEMPTS;
    } else {
      LOG_WARN(OUTPOINT,
               "MQTT reconnect threshold reached, skip toggle during cooldown\r\n");
    }
    disconnectCnt = 0;
    retry_delay = MQTT_RETRY_BASE_DELAY_S;
  }

  if (need_sleep) {
    sleep(retry_delay);
  }
}

int mqtt_send(MQTTClient_message *pubmsg, char *send_topic) {
  if (client == NULL) {
    return MQTTCLIENT_FAILURE;
  }
  // reconnect and subcribe if the status is not connected
  if (!MQTTClient_isConnected(client)) {
    LOG_WARN(OUTPOINT, "The network is not conected,Failed to send msg!\r\n");
    return MQTTCLIENT_FAILURE;
  }
  rc = MQTTClient_publishMessage(client, send_topic, pubmsg, &token);
  if (MQTTCLIENT_SUCCESS != rc)
    return rc;
  LOG_INFO(OUTPOINT,
           "Waiting for up to %d seconds for publication of %d"
           "on topic %s for client with ClientID: %s\n",
           (int)(SEND_TIMEOUT / 1000), rc, send_topic,
           send_topic); // PUBLISH_TOPIC
  rc = MQTTClient_waitForCompletion(client, token, SEND_TIMEOUT);
  if (MQTTCLIENT_SUCCESS != rc) {
    LOG_INFO(OUTPOINT, "send faile code:%d\r\n", rc);
    sen_time++;
    if (sen_time >= MAX_SEND_TIME) {
      mqtt_isConnected = false;
      sen_time = 0;
      LOG_INFO(OUTPOINT, "disconnect:%d\r\n",
               MQTTClient_disconnect(client, REV_TIMEOUT));
    }
    return rc;
  }
  LOG_INFO(OUTPOINT, "Message with delivery token %d delivered\n", token);
  return rc;
}

